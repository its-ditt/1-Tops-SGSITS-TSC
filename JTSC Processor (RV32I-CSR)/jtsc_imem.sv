`timescale 1ns / 1ps

module jtsc_imem(

input  logic [31:0] A,
output logic [31:0] RD

);

always_comb
begin

    case(A)

    //////////////////////////////////////////////////
    // x1 = 10
    //////////////////////////////////////////////////

    32'h00000000: RD = 32'h00A00093; // addi x1,x0,10

    //////////////////////////////////////////////////
    // x2 = 20
    //////////////////////////////////////////////////

    32'h00000004: RD = 32'h01400113; // addi x2,x0,20

    //////////////////////////////////////////////////
    // x3 = x1+x2 = 30
    //////////////////////////////////////////////////

    32'h00000008: RD = 32'h002081B3; // add x3,x1,x2

    //////////////////////////////////////////////////
    // mtvec = x3 (30)
    //////////////////////////////////////////////////

    32'h0000000C: RD = 32'h305190F3; // csrrw x1,mtvec,x3

    //////////////////////////////////////////////////
    // mtvec = 5
    //////////////////////////////////////////////////

    32'h00000010: RD = 32'h3052D173; // csrrwi x2,mtvec,5

    //////////////////////////////////////////////////
    // mtvec |= 2
    //////////////////////////////////////////////////

    32'h00000014: RD = 32'h305161F3; // csrrsi x3,mtvec,2

    //////////////////////////////////////////////////
    // mtvec &= ~1
    //////////////////////////////////////////////////

    32'h00000018: RD = 32'h3050F273; // csrrci x4,mtvec,1

    //////////////////////////////////////////////////
    // ECALL
    //////////////////////////////////////////////////

    32'h0000001C: RD = 32'h00000073;

    //////////////////////////////////////////////////
    // NOPs
    //////////////////////////////////////////////////

    32'h00000020: RD = 32'h00000013;
    32'h00000024: RD = 32'h00000013;
    32'h00000028: RD = 32'h00000013;
    32'h0000002C: RD = 32'h00000013;

    default: RD = 32'h00000013;

    endcase

end

endmodule

